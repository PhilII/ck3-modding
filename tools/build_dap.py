"""Generates Dynasty Autopilot's settings plumbing from tools/dap_settings.py.

Usage: python3 tools/build_dap.py

Writes (all marked GENERATED, never edit them by hand):
  common/scripted_effects/dap_settings_generated.txt
  common/customizable_localization/dap_settings_generated.txt
  localization/english/dap_settings_generated_l_english.yml
  gui/dap_settings_generated.gui
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dap_settings import MODULES, PRESETS, SAVE_SLOTS  # noqa: E402

MOD = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "mods", "dynasty_autopilot")
HEADER = "# GENERATED by tools/build_dap.py from tools/dap_settings.py - do not edit by hand\n"
ROW_HINT = "\\n\\n#weak Click: next option. Right-click: previous option.#!"


def write(rel_path, text):
    path = os.path.normpath(os.path.join(MOD, rel_path))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    # CK3 wants UTF-8 with BOM for script and localization files
    with open(path, "w", encoding="utf-8-sig", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.relpath(path, os.path.join(MOD, "..", "..")))


def settings(holder=None):
    for module in MODULES:
        for section in module["sections"]:
            if holder is None or section["holder"] == holder:
                yield from section["settings"]


def validate():
    seen = set()
    for s in settings():
        key = s["key"]
        assert key.startswith("dap_"), f"{key}: keys need the dap_ prefix"
        assert key not in seen, f"{key}: duplicate key"
        assert 0 <= s["default"] < len(s["values"]), f"{key}: default out of range"
        assert len(s["values"]) >= 2, f"{key}: needs at least two values"
        seen.add(key)
    rule_keys = {s["key"]: s for s in settings("rules")}
    for preset in PRESETS:
        for key, value in preset["values"].items():
            assert key in rule_keys, f"preset {preset['id']}: {key} is not a rules setting"
            assert 0 <= value < len(rule_keys[key]["values"]), f"preset {preset['id']}: {key} out of range"


def build_effects():
    out = [HEADER]

    def set_block(name, holder, comment):
        out.append(f"# {comment}\n{name} = {{\n")
        for s in settings(holder):
            out.append(f"\tset_variable = {{ name = {s['key']} value = {s['default']} }}\n")
        out.append("}\n\n")

    set_block("dap_set_default_player_settings_effect", "player", "this = player; module-wide switches")
    set_block("dap_set_default_rules_effect", "rules", "this = rule holder; default rule values")

    out.append("# this = family member; personal rules start as a copy of $FROM$'s rules\n")
    out.append("dap_copy_rules_effect = {\n\tset_variable = { name = dap_override value = 1 }\n")
    for s in settings("rules"):
        out.append(f"\tset_variable = {{ name = {s['key']} value = $FROM$.var:{s['key']} }}\n")
    out.append("}\n\n")

    out.append("# this = family member; drop personal rules so the defaults apply again\n")
    out.append("dap_clear_rules_effect = {\n\tremove_variable = dap_override\n")
    for s in settings("rules"):
        out.append(f"\tremove_variable = {s['key']}\n")
    out.append("}\n\n")

    def ensure_block(name, holder, comment):
        out.append(f"# {comment}\n{name} = {{\n")
        for st in settings(holder):
            out.append(f"\tif = {{\n\t\tlimit = {{ NOT = {{ has_variable = {st['key']} }} }}\n"
                       f"\t\tset_variable = {{ name = {st['key']} value = {st['default']} }}\n\t}}\n")
        out.append("}\n\n")

    ensure_block("dap_ensure_player_settings_effect", "player",
                 "this = player; adds settings introduced after the save was started")
    ensure_block("dap_ensure_rules_effect", "rules",
                 "this = rule holder; adds rules introduced after the save was started")

    # The GUI passes these flags in, so the script validator never sees them set otherwise
    out.append("# Called from dap_init_player_effect so the validator knows the GUI flags exist\n")
    out.append("dap_declare_setting_flags_effect = {\n")
    flags = [st["key"] for st in settings()] + [f"dap_preset_{pr['id']}" for pr in PRESETS]
    flags += [f"dap_slot_{n}" for n in range(1, SAVE_SLOTS + 1)]
    for flag in flags:
        out.append(f"\tset_local_variable = {{ name = dap_setting_flag value = flag:{flag} }}\n")
    out.append("\tif = {\n\t\tlimit = { exists = local_var:dap_setting_flag }\n"
               "\t\tremove_local_variable = dap_setting_flag\n\t}\n}\n\n")

    out.append("# this = rule holder; scope:preset = flag naming the preset\ndap_apply_preset_effect = {\n"
               "\tdap_set_default_rules_effect = yes\n")
    for i, preset in enumerate(PRESETS):
        kw = "if" if i == 0 else "else_if"
        out.append(f"\t{kw} = {{\n\t\tlimit = {{ scope:preset = flag:dap_preset_{preset['id']} }}\n")
        for key, value in preset["values"].items():
            out.append(f"\t\tset_variable = {{ name = {key} value = {value} }}\n")
        out.append("\t}\n")
    out.append("}\n\n")

    out.append("# root = player, scope:holder = rule holder; stores the holder's rules in slot $SLOT$\n"
               "dap_save_slot_effect = {\n\troot = {\n\t\tset_variable = { name = dap_slot$SLOT$_saved value = 1 }\n")
    for st in settings("rules"):
        out.append(f"\t\tset_variable = {{ name = dap_slot$SLOT$_{st['key']} value = scope:holder.var:{st['key']} }}\n")
    out.append("\t}\n}\n\n")

    out.append("# this = rule holder, root = player; loads slot $SLOT$ into the holder\ndap_load_slot_effect = {\n"
               "\tif = {\n\t\tlimit = { root = { has_variable = dap_slot$SLOT$_saved } }\n")
    for st in settings("rules"):
        out.append(f"\t\tset_variable = {{ name = {st['key']} value = root.var:dap_slot$SLOT$_{st['key']} }}\n")
    out.append("\t}\n}\n\n")

    out.append("# this = player; park the default rules while a saved rule set is loaded in their place\n"
               "dap_stash_rules_effect = {\n")
    for st in settings("rules"):
        out.append(f"\tset_variable = {{ name = dap_stash_{st['key']} value = var:{st['key']} }}\n")
    out.append("}\n\n")
    out.append("# this = player; put the parked default rules back\ndap_restore_rules_effect = {\n")
    for st in settings("rules"):
        out.append(f"\tset_variable = {{ name = {st['key']} value = var:dap_stash_{st['key']} }}\n")
        out.append(f"\tremove_variable = dap_stash_{st['key']}\n")
    out.append("}\n\n")

    for name, inner in (("dap_save_slot_by_flag_effect", "dap_save_slot_effect"),
                        ("dap_load_slot_by_flag_effect", "dap_load_slot_effect")):
        out.append(f"# scope:slot = flag naming the slot\n{name} = {{\n")
        for n in range(1, SAVE_SLOTS + 1):
            kw = "if" if n == 1 else "else_if"
            out.append(f"\t{kw} = {{\n\t\tlimit = {{ scope:slot = flag:dap_slot_{n} }}\n"
                       f"\t\t{inner} = {{ SLOT = {n} }}\n\t}}\n")
        out.append("}\n\n")

    for name, helper in (("dap_setting_next_effect", "dap_cycle_effect"),
                         ("dap_setting_prev_effect", "dap_cycle_back_effect")):
        out.append(f"# this = setting holder; scope:setting = flag naming the setting\n{name} = {{\n")
        first = True
        for s in settings():
            kw = "if" if first else "else_if"
            first = False
            out.append(f"\t{kw} = {{\n\t\tlimit = {{ scope:setting = flag:{s['key']} }}\n"
                       f"\t\t{helper} = {{ VAR = {s['key']} MAX = {len(s['values']) - 1} }}\n\t}}\n")
        out.append("}\n\n")

    write("common/scripted_effects/dap_settings_generated.txt", "".join(out))


def build_custom_loc():
    out = [HEADER]
    for s in settings():
        out.append(f"dap_cl_{s['key']} = {{\n\ttype = character\n")
        for i in range(len(s["values"])):
            out.append(f"\ttext = {{\n\t\ttrigger = {{ var:{s['key']} = {i} }}\n"
                       f"\t\tlocalization_key = dap_val_{s['key']}_{i}\n\t}}\n")
        out.append("\ttext = {\n\t\tfallback = yes\n\t\tlocalization_key = dap_val_unset\n\t}\n}\n\n")
    write("common/customizable_localization/dap_settings_generated.txt", "".join(out))


def loc_escape(text):
    return text.replace('"', '\\"')


def build_loc():
    out = ["l_english:\n", " " + HEADER.replace("\n", "") + "\n", ' dap_val_unset: "?"\n']
    for module in MODULES:
        out.append(f' dap_tab_{module["id"]}: "{loc_escape(module["tab"])}"\n')
        for section in module["sections"]:
            out.append(f' dap_section_{module["id"]}_{section["id"]}: "{loc_escape(section["title"])}"\n')
            for s in section["settings"]:
                out.append(f' dap_setting_{s["key"]}: "{loc_escape(s["label"])}"\n')
                out.append(f' dap_setting_{s["key"]}_tt: "{loc_escape(s["tooltip"])}{ROW_HINT}"\n')
                for i, value in enumerate(s["values"]):
                    out.append(f' dap_val_{s["key"]}_{i}: "{loc_escape(value)}"\n')
    for preset in PRESETS:
        out.append(f' dap_preset_{preset["id"]}: "{loc_escape(preset["label"])}"\n')
        out.append(f' dap_preset_{preset["id"]}_tt: "{loc_escape(preset["tooltip"])}\\n\\n#weak Replaces all rules shown below.#!"\n')
    for n in range(1, SAVE_SLOTS + 1):
        out.append(f' dap_slot_save_{n}: "Save {n}"\n')
        out.append(f' dap_slot_load_{n}: "Load {n}"\n')
        out.append(f' dap_slot_save_{n}_tt: "Save the rules shown below in slot {n}."\n')
        out.append(f' dap_slot_load_{n}_tt: "Replace the rules shown below with the ones saved in slot {n}."\n')
    write("localization/english/dap_settings_generated_l_english.yml", "".join(out))


def sgui_call(sgui, key, scope_name="setting"):
    return (f"[GetScriptedGui( '{sgui}' ).Execute( GuiScope.SetRoot( GetPlayer.MakeScope )"
            f".AddScope( 'holder', Character.MakeScope )"
            f".AddScope( '{scope_name}', MakeScopeFlag( '{key}' ) ).End )]")


def build_gui():
    out = [HEADER, "# Rows read and write the settings of the datacontext Character (see dap_window.gui)\n",
           "types DapSettingsGenerated\n{\n"]
    for module in MODULES:
        for section in module["sections"]:
            out.append(f"\ttype dap_section_{module['id']}_{section['id']} = vbox {{\n"
                       "\t\tlayoutpolicy_horizontal = expanding\n\n"
                       "\t\tdap_section_header = {\n"
                       f"\t\t\tblockoverride \"title\" {{ text = \"dap_section_{module['id']}_{section['id']}\" }}\n"
                       "\t\t}\n")
            for s in section["settings"]:
                key = s["key"]
                out.append(
                    "\t\tdap_setting_row = {\n"
                    f"\t\t\tblockoverride \"label\" {{ text = \"dap_setting_{key}\" }}\n"
                    f"\t\t\tblockoverride \"tooltip\" {{ tooltip = \"dap_setting_{key}_tt\" }}\n"
                    f"\t\t\tblockoverride \"value\" {{ text = \"[Character.Custom( 'dap_cl_{key}' )]\" }}\n"
                    f"\t\t\tblockoverride \"onclick\" {{ onclick = \"{sgui_call('dap_setting_next', key)}\" }}\n"
                    f"\t\t\tblockoverride \"onrightclick\" {{ onrightclick = \"{sgui_call('dap_setting_prev', key)}\" }}\n"
                    "\t\t}\n")
            out.append("\t}\n\n")

        # One type per holder kind, so the window never lists sections by name
        for holder in ("player", "rules"):
            out.append(f"\ttype dap_module_{module['id']}_{holder} = vbox {{\n"
                       "\t\tlayoutpolicy_horizontal = expanding\n")
            for section in module["sections"]:
                if section["holder"] == holder:
                    out.append(f"\t\tdap_section_{module['id']}_{section['id']} = {{}}\n")
            out.append("\t}\n\n")

    # Tabs and views: the window places these and never names a module itself
    out.append("\ttype dap_tab_buttons = hbox {\n\t\tlayoutpolicy_horizontal = expanding\n\t\tmargin = { 10 0 }\n")
    for module in MODULES:
        out.append("\t\tbutton_tab = {\n\t\t\tlayoutpolicy_horizontal = expanding\n"
                   f"\t\t\ttext = \"dap_tab_{module['id']}\"\n"
                   f"\t\t\tonclick = \"[GetVariableSystem.Set( 'dap_tab', '{module['id']}' )]\"\n"
                   f"\t\t\tdown = \"[GetVariableSystem.HasValue( 'dap_tab', '{module['id']}' )]\"\n\t\t}}\n")
    out.append("\t}\n\n")

    def tab_is(module_id):
        return f"GetVariableSystem.HasValue( 'dap_tab', '{module_id}' )"

    out.append("\ttype dap_settings_view = vbox {\n\t\tlayoutpolicy_horizontal = expanding\n")
    for module in MODULES:
        if any(sec["holder"] == "player" for sec in module["sections"]):
            out.append(f"\t\tdap_module_{module['id']}_player = {{\n\t\t\tvisible = \"[{tab_is(module['id'])}]\"\n\t\t}}\n")
    out.append("\t}\n\n")

    out.append("\ttype dap_rules_view = vbox {\n\t\tlayoutpolicy_horizontal = expanding\n")
    rule_modules = [m["id"] for m in MODULES if any(sec["holder"] == "rules" for sec in m["sections"])]
    for module_id in rule_modules:
        out.append(f"\t\tdap_module_{module_id}_rules = {{\n\t\t\tvisible = \"[{tab_is(module_id)}]\"\n\t\t}}\n")
    out.append("\t}\n\n")

    # Nested Or() over every module that has per-person rules
    expr = tab_is(rule_modules[-1])
    for module_id in reversed(rule_modules[:-1]):
        expr = f"Or( {tab_is(module_id)}, {expr} )"
    view_is_rules = "GetVariableSystem.HasValue( 'dap_view', 'rules' )"
    templates = [
        ("dap_rules_tab_visible", f"[{expr}]"),
        ("dap_show_rules_view", f"[And( {expr}, {view_is_rules} )]"),
        ("dap_show_settings_view", f"[Or( Not( {expr} ), Not( {view_is_rules} ) )]"),
    ]

    out.append("\ttype dap_presets_row = hbox {\n\t\tspacing = 6\n")
    for preset in PRESETS:
        out.append("\t\tbutton_standard = {\n\t\t\tsize = { 120 30 }\n"
                   f"\t\t\ttext = \"dap_preset_{preset['id']}\"\n"
                   f"\t\t\ttooltip = \"dap_preset_{preset['id']}_tt\"\n"
                   f"\t\t\tonclick = \"{sgui_call('dap_apply_preset', 'dap_preset_' + preset['id'], 'preset')}\"\n"
                   "\t\t}\n")
    out.append("\t}\n\n")

    out.append("\ttype dap_slots_row = hbox {\n\t\tspacing = 6\n")
    for n in range(1, SAVE_SLOTS + 1):
        out.append("\t\tbutton_standard_small = {\n\t\t\tsize = { 70 26 }\n"
                   f"\t\t\ttext = \"dap_slot_save_{n}\"\n\t\t\ttooltip = \"dap_slot_save_{n}_tt\"\n"
                   f"\t\t\tonclick = \"{sgui_call('dap_save_slot', f'dap_slot_{n}', 'slot')}\"\n\t\t}}\n"
                   "\t\tbutton_standard_small = {\n\t\t\tsize = { 70 26 }\n"
                   f"\t\t\ttext = \"dap_slot_load_{n}\"\n\t\t\ttooltip = \"dap_slot_load_{n}_tt\"\n"
                   f"\t\t\tenabled = \"[GetPlayer.MakeScope.Var('dap_slot{n}_saved').IsSet]\"\n"
                   f"\t\t\tonclick = \"{sgui_call('dap_load_slot', f'dap_slot_{n}', 'slot')}\"\n\t\t}}\n")
    out.append("\t}\n}\n\n")
    for name, visible in templates:
        out.append(f"template {name}\n{{\n\tvisible = \"{visible}\"\n}}\n\n")
    write("gui/dap_settings_generated.gui", "".join(out))


LANGUAGES = ["french", "german", "spanish", "russian", "korean", "simp_chinese", "polish", "japanese"]


def build_translations():
    """Other languages get the English text, so players never see raw keys."""
    english = os.path.join(MOD, "localization", "english")
    for name in sorted(os.listdir(english)):
        if not name.endswith("_l_english.yml"):
            continue
        with open(os.path.join(english, name), encoding="utf-8-sig") as f:
            text = f.read()
        for language in LANGUAGES:
            translated = text.replace("l_english:", f"l_{language}:\n # GENERATED copy of the English text by tools/build_dap.py", 1)
            target = name.replace("_l_english.yml", f"_l_{language}.yml")
            write(os.path.join("localization", language, target), translated)


if __name__ == "__main__":
    validate()
    build_effects()
    build_custom_loc()
    build_loc()
    build_gui()
    build_translations()
