"""Generates Dynasty Autopilot's building data from the installed game's building files.

Usage: python3 tools/build_buildings.py [--game PATH]

Run it after game patches and commit the result. It needs the game files, so CI
does not run it. Writes (all marked GENERATED, never edit them by hand):
  common/scripted_triggers/dap_buildings_generated.txt
  common/scripted_effects/dap_buildings_generated.txt
  common/customizable_localization/dap_buildings_generated.txt

Development buildings are regular buildings whose county_modifier raises
development growth (county reach). Only the first level of each chain is listed:
the builder starts new buildings in free slots, it does not upgrade yet.
"""

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.join(HERE, "..", "mods", "dynasty_autopilot")
DEFAULT_GAME = os.path.expanduser("~/Library/Application Support/Steam/steamapps/common/Crusader Kings III/game")
HEADER = "# GENERATED by tools/build_buildings.py from the game's building files - do not edit by hand\n"

# The game's requirement triggers, all of which must hold for the Build button to work
REQUIREMENT_BLOCKS = ("is_enabled", "can_construct_potential", "can_construct", "can_construct_showing_failures_only")
DEVELOPMENT_MODIFIERS = ("development_growth", "development_growth_factor")

TOKEN = re.compile(r'"(?:[^"\\]|\\.)*"|@\[[^\]]*\]|[{}]|[<>!?=]=|[<>=]|[^\s{}<>!?="]+')
OPERATORS = {"=", "!=", "<=", ">=", "<", ">", "?=", "=="}


def tokenize(text):
    text = "\n".join(re.sub(r'#(?=(?:[^"]*"[^"]*")*[^"]*$).*', "", line) for line in text.split("\n"))
    return TOKEN.findall(text)


def parse(tokens, pos=0):
    """A block as a list of (key, op, value) entries; bare list items have key None."""
    items = []
    while pos < len(tokens):
        tok = tokens[pos]
        if tok == "}":
            return items, pos + 1
        if pos + 1 < len(tokens) and tokens[pos + 1] in OPERATORS:
            op = tokens[pos + 1]
            if tokens[pos + 2] == "{":
                value, pos = parse(tokens, pos + 3)
            else:
                value, pos = tokens[pos + 2], pos + 3
            items.append((tok, op, value))
        elif tok == "{":
            value, pos = parse(tokens, pos + 1)
            items.append((None, None, value))
        else:
            items.append((None, None, tok))
            pos += 1
    return items, pos


def get(block, key):
    for k, _, v in block:
        if k == key:
            return v
    return None


def serialize(block, depth):
    out = []
    pad = "\t" * depth
    for key, op, value in block:
        if isinstance(value, list):
            head = f"{key} {op} " if key is not None else ""
            out.append(f"{pad}{head}{{\n{serialize(value, depth + 1)}{pad}}}\n")
        else:
            out.append(f"{pad}{key} {op} {value}\n" if key is not None else f"{pad}{value}\n")
    return "".join(out)


def read(path):
    with open(path, encoding="utf-8-sig") as f:
        return f.read()


def script_files(game, folder):
    path = os.path.join(game, "common", folder)
    return [os.path.join(path, n) for n in sorted(os.listdir(path)) if n.endswith(".txt")]


def evaluate(expr, constants):
    """Value of a number, @constant or @[formula] from the game's script values."""
    if expr.startswith("@["):
        formula = re.sub(r"[A-Za-z_]\w*", lambda m: f"({constants[m.group(0)]})", expr[2:-1])
        return eval(formula, {"__builtins__": {}})  # game data, arithmetic only
    if expr.startswith("@"):
        return constants[expr[1:]]
    return float(expr)


def cost_values(game):
    """Gold value of every named cost (e.g. expensive_building_tier_1_cost)."""
    constants, values = {}, {}
    for path in script_files(game, "script_values"):
        for key, op, value in parse(tokenize(read(path)))[0]:
            if key and key.startswith("@") and isinstance(value, str):
                constants[key[1:]] = evaluate(value, constants)
            elif key and isinstance(value, str) and key.endswith("_cost"):
                try:
                    values[key] = evaluate(value, constants)
                except (KeyError, ValueError, SyntaxError):
                    pass
    return values


def load_buildings(game):
    found = {}
    for path in script_files(game, "buildings"):
        for key, _, value in parse(tokenize(read(path)))[0]:
            if key and not key.startswith("@") and isinstance(value, list):
                found[key] = value
    return found


def development_buildings(game):
    """(key, cost value name, gold) of each first-level regular development building, cheapest first."""
    all_buildings = load_buildings(game)
    upgrades = {get(building, "next_building") for building in all_buildings.values()}
    costs = cost_values(game)
    result = []
    for key, building in all_buildings.items():
        county = get(building, "county_modifier") or []
        if (key in upgrades or (get(building, "type") or "regular") != "regular"
                or get(building, "is_graphical_background") == "yes"
                or not any(k in DEVELOPMENT_MODIFIERS for k, _, _ in county)):
            continue
        cost = get(building, "cost_gold")
        # Buildings that also cost prestige, piety or the like are left to the player
        if cost is None or get(building, "cost") is not None or cost not in costs:
            continue
        result.append((key, cost, costs[cost]))
    return sorted(result, key=lambda r: (r[2], r[0]))


def requirement_trigger(key, building):
    body = [f"\tNOT = {{ has_building_or_higher = {key} }}\n"]
    for name in REQUIREMENT_BLOCKS:
        block = get(building, name)
        if block:
            text = serialize(block, 1)
            assert "@" not in text and not re.search(r"\broot\b", text), f"{key}.{name} needs its own scope handling"
            body.append(f"\t# {name}\n{text}")
    return f"dap_can_build_{key}_trigger = {{\n{''.join(body)}}}\n\n"


def write(rel_path, text):
    path = os.path.normpath(os.path.join(MOD, rel_path))
    with open(path, "w", encoding="utf-8-sig", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.relpath(path, os.path.join(MOD, "..", "..")))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--game", default=DEFAULT_GAME, help="the game's game/ folder")
    args = parser.parse_args()
    if not os.path.isdir(os.path.join(args.game, "common", "buildings")):
        sys.exit(f"No building files under {args.game}")

    all_buildings = load_buildings(args.game)
    development = development_buildings(args.game)
    assert development, "no development buildings found; did the game's files change?"

    triggers = [HEADER, "# this = province; scope:holder = its holder, scope:county = its county (as the game's\n"
                        "# building triggers expect). True when the building can be started there.\n\n"]
    triggers += [requirement_trigger(key, all_buildings[key]) for key, _, _ in development]
    write("common/scripted_triggers/dap_buildings_generated.txt", "".join(triggers))

    effects = [HEADER, "# this = province, with scope:holder and scope:county saved; saves the cheapest development\n"
                       "# building that can be started there as scope:dap_build_building (flag:<building key>)\n"
                       "# and its base price as scope:dap_build_cost\n",
               "dap_pick_development_building_effect = {\n"]
    for i, (key, cost, _) in enumerate(development):
        effects.append(f"\t{'if' if i == 0 else 'else_if'} = {{\n\t\tlimit = {{ dap_can_build_{key}_trigger = yes }}\n"
                       f"\t\tsave_scope_value_as = {{ name = dap_build_building value = flag:{key} }}\n"
                       f"\t\tsave_scope_value_as = {{ name = dap_build_cost value = {cost} }}\n\t}}\n")
    effects.append("}\n")
    write("common/scripted_effects/dap_buildings_generated.txt", "".join(effects))

    loc = [HEADER, "# Name of the building in var:dap_log_building (a log entry)\n",
           "dap_cl_log_building = {\n\ttype = character\n"]
    for key, _, _ in development:
        loc.append(f"\ttext = {{\n\t\ttrigger = {{ var:dap_log_building ?= flag:{key} }}\n"
                   f"\t\tlocalization_key = building_{key}\n\t}}\n")
    loc.append("\ttext = {\n\t\tfallback = yes\n\t\tlocalization_key = dap_empty\n\t}\n}\n")
    write("common/customizable_localization/dap_buildings_generated.txt", "".join(loc))


if __name__ == "__main__":
    main()
