"""Generates Dynasty Autopilot's building data from the installed game's building files.

Usage: python3 tools/build_buildings.py [--game PATH]

Run it after game patches and commit the result. It needs the game files, so CI
does not run it. Writes (all marked GENERATED, never edit them by hand):
  common/scripted_triggers/dap_buildings_generated.txt
  common/scripted_effects/dap_buildings_generated.txt
  common/customizable_localization/dap_buildings_generated.txt

Every regular building is listed: its requirement triggers, cost and construction
time (the game's named script values), next level, and its focus scores split by
the reach of each bonus (county_modifier = county, province_modifier = holding,
character_modifier = holder). First levels are new buildings for free slots; later
levels are upgrades of the level before, scored by what they add. The holdings'
main buildings (castle, city, temple...) come with the holding, so only their
upgrades are listed. The scripted effects file ends with a list of every regular
building that is left out, and why.
"""

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.join(HERE, "..", "mods", "dynasty_autopilot")
DEFAULT_GAME = os.path.expanduser("~/Library/Application Support/Steam/steamapps/common/Crusader Kings III/game")
HEADER = "# GENERATED by tools/build_buildings.py from the game's building files - do not edit by hand\n"

# The game's requirement triggers, all of which must hold for the Build button to work
REQUIREMENT_BLOCKS = ("is_enabled", "can_construct_potential", "can_construct", "can_construct_showing_failures_only")

TOKEN = re.compile(r'"(?:[^"\\]|\\.)*"|@\[[^\]]*\]|[{}]|[<>!?=]=|[<>=]|[^\s{}<>!?="]+')
OPERATORS = {"=", "!=", "<=", ">=", "<", ">", "?=", "=="}


def tokenize(text):
    text = "\n".join(re.sub(r'#(?=(?:[^"]*"[^"]*")*[^"]*$).*', "", line) for line in text.split("\n"))
    return TOKEN.findall(text)


def parse(tokens, pos=0):
    """A block as a list of (key, op, value) entries; bare list items have key None."""
    items = []
    while pos < len(tokens):
        tok = tokens[pos]
        if tok == "}":
            return items, pos + 1
        if pos + 1 < len(tokens) and tokens[pos + 1] in OPERATORS:
            op = tokens[pos + 1]
            if tokens[pos + 2] == "{":
                value, pos = parse(tokens, pos + 3)
            else:
                value, pos = tokens[pos + 2], pos + 3
            items.append((tok, op, value))
        elif tok == "{":
            value, pos = parse(tokens, pos + 1)
            items.append((None, None, value))
        else:
            items.append((None, None, tok))
            pos += 1
    return items, pos


def get(block, key):
    for k, _, v in block:
        if k == key:
            return v
    return None


def serialize(block, depth):
    out = []
    pad = "\t" * depth
    for key, op, value in block:
        if isinstance(value, list):
            head = f"{key} {op} " if key is not None else ""
            out.append(f"{pad}{head}{{\n{serialize(value, depth + 1)}{pad}}}\n")
        else:
            out.append(f"{pad}{key} {op} {value}\n" if key is not None else f"{pad}{value}\n")
    return "".join(out)


def read(path):
    with open(path, encoding="utf-8-sig") as f:
        return f.read()


def script_files(game, folder):
    path = os.path.join(game, "common", folder)
    return [os.path.join(path, n) for n in sorted(os.listdir(path)) if n.endswith(".txt")]


def evaluate(expr, constants):
    """Value of a number, @constant or @[formula] from the game's script values."""
    if expr.startswith("@["):
        formula = re.sub(r"[A-Za-z_]\w*", lambda m: f"({constants[m.group(0)]})", expr[2:-1])
        return eval(formula, {"__builtins__": {}})  # game data, arithmetic only
    if expr.startswith("@"):
        return constants[expr[1:]]
    return float(expr)


def named_values(game):
    """Number behind every named script value (e.g. expensive_building_tier_1_cost)."""
    constants, values = {}, {}
    for path in script_files(game, "script_values"):
        for key, op, value in parse(tokenize(read(path)))[0]:
            if key and key.startswith("@") and isinstance(value, str):
                constants[key[1:]] = evaluate(value, constants)
            elif key and isinstance(value, str):
                try:
                    values[key] = evaluate(value, constants)
                except (KeyError, ValueError, SyntaxError, NameError):
                    pass
    return values


def load_buildings(game):
    found = {}
    for path in script_files(game, "buildings"):
        for key, _, value in parse(tokenize(read(path)))[0]:
            if key and not key.startswith("@") and isinstance(value, list):
                found[key] = value
    return found


def main_buildings(game):
    """The first level of each holding type's main building (castle_01, city_01...)."""
    return {get(holding, "primary_building")
            for path in script_files(game, "holdings")
            for key, _, holding in parse(tokenize(read(path)))[0]
            if isinstance(holding, list) and get(holding, "primary_building")}


# Income is valued in gold per month. A tax_mult bonus is worth that share of a holding's
# tax, estimated at TAX_PER_HOLDING gold a month; in the county block it reaches every
# holding there, estimated at HOLDINGS_PER_COUNTY.
TAX_PER_HOLDING = 1.0
HOLDINGS_PER_COUNTY = 2.5
# Development is valued in development growth; development_growth_factor multiplies the
# county's own growth, estimated at FACTOR_BASE_GROWTH.
FACTOR_BASE_GROWTH = 0.5
REACH_BLOCKS = {"county_modifier": "COUNTY", "province_modifier": "HOLDING", "character_modifier": "HOLDER"}
SCORES = ("INCOME_HOLDING", "INCOME_HOLDER", "INCOME_COUNTY", "DEVELOPMENT_COUNTY")


def number(expr, values):
    try:
        return float(expr)
    except ValueError:
        return values.get(expr, 0.0)


def raw_scores(building, values):
    """Income (gold/month) by reach and development growth (county reach), before scaling."""
    scores = dict.fromkeys(SCORES, 0.0)
    for block, reach in REACH_BLOCKS.items():
        for key, _, value in get(building, block) or []:
            if isinstance(value, list):
                continue
            amount = number(value, values)
            if key == "monthly_income":
                scores[f"INCOME_{reach}"] += amount
            elif key == "tax_mult":
                share = HOLDINGS_PER_COUNTY if reach == "COUNTY" else 1.0
                scores[f"INCOME_{reach}"] += amount * TAX_PER_HOLDING * share
            elif key in ("development_growth", "development_growth_factor") and reach == "COUNTY":
                factor = FACTOR_BASE_GROWTH if key.endswith("_factor") else 1.0
                scores["DEVELOPMENT_COUNTY"] += amount * factor
    return scores


def median(numbers):
    numbers = sorted(numbers)
    return numbers[len(numbers) // 2] if numbers else 1.0


def requirement_trigger(key, building, previous):
    """Body of the trigger that the building can be started there, or None if it cannot be copied."""
    if previous:
        body = [f"\thas_building = {previous}\n"]
    else:
        body = [f"\tNOT = {{ has_building_or_higher = {key} }}\n"]
    for name in REQUIREMENT_BLOCKS:
        block = get(building, name)
        if block:
            text = serialize(block, 1)
            if "@" in text or re.search(r"\broot\b", text):
                return None
            body.append(f"\t# {name}\n{text}")
    return "".join(body)


def candidates(game):
    """(candidates, skipped): each candidate a dict for one regular building, in a stable
    order (new buildings, then upgrades, each by key); skipped as (key, reason)."""
    buildings = load_buildings(game)
    values = named_values(game)
    mains = main_buildings(game)
    previous = {}
    for key, building in buildings.items():
        nxt = get(building, "next_building")
        if nxt:
            previous[nxt] = key
    chain_of_main = set()
    for main in mains:
        key = main
        while key:
            chain_of_main.add(key)
            key = get(buildings.get(key, []), "next_building")

    found, skipped = [], []
    for key in sorted(buildings):
        building = buildings[key]
        if (get(building, "type") or "regular") != "regular":
            continue
        cost = get(building, "cost_gold")
        prev = previous.get(key)
        reason = None
        if get(building, "is_graphical_background") == "yes":
            reason = "background only"
        elif key in mains:
            reason = "comes with its holding"
        elif cost is None or cost not in values:
            reason = "no gold cost"
        elif get(building, "cost") is not None:
            reason = "also costs prestige or piety"
        elif prev and (get(buildings[prev], "type") or "regular") != "regular":
            reason = "upgrade of a building that is not regular"
        if reason is None:
            trigger = requirement_trigger(key, building, prev)
            if trigger is None:
                reason = "requirements need their own scope handling"
        if reason:
            skipped.append((key, reason))
            continue
        scores = raw_scores(building, values)
        if prev:
            before = raw_scores(buildings[prev], values)
            scores = {s: scores[s] - before[s] for s in SCORES}
        found.append({
            "key": key, "previous": prev, "cost": cost, "gold": values[cost],
            "time": get(building, "construction_time"), "next": get(building, "next_building"),
            "main": key in chain_of_main, "trigger": trigger, "scores": scores,
        })

    # Weigh development against income: a typical development building gives as much
    # development per gold as a typical income building gives income per gold, so Low and
    # High mean the same for both focuses
    income = [sum(c["scores"][s] for s in SCORES[:3]) / c["gold"] for c in found
              if not c["previous"] and sum(c["scores"][s] for s in SCORES[:3]) > 0]
    development = [c["scores"]["DEVELOPMENT_COUNTY"] / c["gold"] for c in found
                   if not c["previous"] and c["scores"]["DEVELOPMENT_COUNTY"] > 0]
    scale = median(income) / median(development)
    for c in found:
        c["scores"]["DEVELOPMENT_COUNTY"] *= scale
    found.sort(key=lambda c: (c["previous"] is not None, c["key"]))
    return found, skipped


def fmt(x):
    return f"{max(x, 0.0):.3f}"


def write(rel_path, text):
    path = os.path.normpath(os.path.join(MOD, rel_path))
    with open(path, "w", encoding="utf-8-sig", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.relpath(path, os.path.join(MOD, "..", "..")))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--game", default=DEFAULT_GAME, help="the game's game/ folder")
    args = parser.parse_args()
    if not os.path.isdir(os.path.join(args.game, "common", "buildings")):
        sys.exit(f"No building files under {args.game}")

    found, skipped = candidates(args.game)
    assert any(c["scores"]["DEVELOPMENT_COUNTY"] > 0 for c in found), "no development buildings; did the game's files change?"

    triggers = [HEADER, "# this = province; scope:holder = its holder, scope:county = its county (as the game's\n"
                        "# building triggers expect). True when the building can be started there: a new\n"
                        "# building in a free slot, or an upgrade of the level before it.\n\n"]
    triggers += [f"dap_can_build_{c['key']}_trigger = {{\n{c['trigger']}}}\n\n" for c in found]
    write("common/scripted_triggers/dap_buildings_generated.txt", "".join(triggers))

    def consider(c, depth):
        pad = "\t" * depth
        s = c["scores"]
        return (f"{pad}if = {{\n{pad}\tlimit = {{ dap_can_build_{c['key']}_trigger = yes }}\n"
                f"{pad}\t# next level: {c['next'] or 'none'}; construction time: {c['time']}\n"
                f"{pad}\tdap_consider_building_effect = {{ BUILDING = {c['key']} FROM = {c['previous'] or 'none'} "
                f"COST = {c['cost']} " + " ".join(f"{name} = {fmt(s[name])}" for name in SCORES) + f" }}\n{pad}}}\n")

    useful = [c for c in found if any(v > 0 for v in c["scores"].values())]
    effects = [HEADER,
               "# this = province, with scope:holder and scope:county saved. Offers every new building that\n"
               "# can go in a free slot there, and every upgrade of a building there, to\n"
               "# dap_consider_building_effect. Scores: income in gold a month and development growth\n"
               "# (weighed to match income), by the reach of the bonus; upgrades score what they add.\n",
               "dap_consider_buildings_effect = {\n\tif = {\n\t\tlimit = { has_free_building_slot = yes }\n"]
    effects += [consider(c, 2) for c in useful if not c["previous"]]
    effects.append("\t}\n")
    effects += [consider(c, 1) for c in useful if c["previous"]]
    effects.append("}\n\n# Regular buildings that serve neither focus (cost, construction time, next level):\n"
                   + "".join(f"#   {c['key']}: {c['cost']}, {c['time']}, {c['next'] or 'none'}\n"
                             for c in found if c not in useful))
    effects.append("# Regular buildings left out:\n" + "".join(f"#   {k}: {r}\n" for k, r in skipped))
    write("common/scripted_effects/dap_buildings_generated.txt", "".join(effects))

    loc = [HEADER, "# Name of the building in var:dap_log_building (a log entry)\n",
           "dap_cl_log_building = {\n\ttype = character\n"]
    for c in useful:
        loc.append(f"\ttext = {{\n\t\ttrigger = {{ var:dap_log_building ?= flag:{c['key']} }}\n"
                   f"\t\tlocalization_key = building_{c['key']}\n\t}}\n")
    loc.append("\ttext = {\n\t\tfallback = yes\n\t\tlocalization_key = dap_empty\n\t}\n}\n")
    write("common/customizable_localization/dap_buildings_generated.txt", "".join(loc))


if __name__ == "__main__":
    main()
